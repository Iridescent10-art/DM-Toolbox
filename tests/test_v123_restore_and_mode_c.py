def test_1_safe_force_remove_locked_file():
    print("[TEST 1] Testing triple-layer force unlock on locked DLL...")
    td = tempfile.mkdtemp()
    h = None
    try:
        src_dll = r"C:\Windows\System32\version.dll"
        test_file = Path(td) / "winmm.dll"
        shutil.copy2(src_dll, str(test_file))
        assert test_file.exists(), "Test file should exist before test"

        # Simulate game process having loaded winmm.dll into memory
        h = ctypes.windll.kernel32.LoadLibraryW(str(test_file))
        assert h, "DLL should be loaded into process memory"

        # Direct deletion of a loaded DLL fails on Windows with WinError 5 / PermissionError.
        # safe_force_remove should trigger Layer 3 atomic rename to bypass lock!
        success = safe_force_remove(str(test_file))
        assert success, "safe_force_remove should return True for locked file"
        assert not test_file.exists(), "Original winmm.dll must no longer exist in target dir!"
        
        # Verify trash file was generated
        locked_tmps = list(Path(td).glob("*._locked_*.tmp"))
        assert len(locked_tmps) > 0, "Locked tmp file should be generated by Layer 3"
        print(f"  -> Layer 3 atomic rename succeeded! Original cleared, moved to: {locked_tmps[0].name}")
    finally:
        if h:
            while ctypes.windll.kernel32.FreeLibrary(h):
                pass
        cleanup_pending_files(td)
        shutil.rmtree(td, ignore_errors=True)
    print("  -> Pending cleanup sweep verified successfully.")


