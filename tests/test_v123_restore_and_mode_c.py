def test_3_mode_c_embedded_assets_integrity():
    print("[TEST 3] Testing Mode C (OptiScaler) embedded components completeness & sizes...")
    updater = ComponentUpdater()
    opti_dir = updater.get_latest_cached_dir(BackendType.OPTISCALER_FSR)
    assert opti_dir and os.path.exists(opti_dir), f"OptiScaler dir not found: {opti_dir}"

    opti_path = Path(opti_dir)
    required_files = {
        "OptiScaler.dll": 1_000_000,
        "dlssg_to_fsr3_amd_is_better.dll": 500_000,
        "amd_fidelityfx_framegeneration_dx12.dll": 10_000_000,
        "amd_fidelityfx_upscaler_dx12.dll": 5_000_000,
        "amd_fidelityfx_dx12.dll": 10_000,
        "amd_fidelityfx_vk.dll": 1_000_000,
        "libxess.dll": 10_000_000,
        "libxess_fg.dll": 5_000_000,
        "libxell.dll": 100_000,
        "OptiScaler.ini": 5_000,
        "D3D12_Optiscaler/D3D12Core.dll": 1_000_000,
    }

    for rel_path, min_bytes in required_files.items():
        f = opti_path / rel_path
        if not f.exists():
            f = opti_path / "OptiScaler" / rel_path
        if not f.exists():
            for c in opti_path.rglob(Path(rel_path).name):
                f = c
                break
        if not f.exists() and rel_path == "amd_fidelityfx_dx12.dll":
            f = opti_path / "OptiScaler" / "amd_fidelityfx_loader_dx12.dll"
        assert f.exists(), f"Missing required Mode C component: {rel_path}"
        sz = f.stat().st_size
        assert sz >= min_bytes, f"Component {rel_path} is undersized: {sz} bytes (expected >= {min_bytes})"
        print(f"  [OK] {rel_path:40s} {sz:>10,d} bytes")
    print("  -> All Mode C components verified intact and full production size!")


def test_4_mode_c_mutual_exclusivity_and_crash_prevention():
    print("[TEST 4] Testing Mode C mutual exclusivity, anti-crash configs, and smart fakenvapi...")
    td = tempfile.mkdtemp()
    target_dir = Path(td)
    try:
        # Create dummy game structure with native Streamline (qualified)
        (target_dir / "yysls.exe").write_bytes(b"FAKE_YYSLS_EXE")
        (target_dir / "sl.interposer.dll").write_bytes(b"FAKE_STREAMLINE_INTERPOSER")

        # Simulate prior Mode B injection
        (target_dir / "renodx-mfgunlock.addon64").write_bytes(b"FAKE_RENODX_ADDON")
        (target_dir / "dxgi.dll").write_bytes(b"ReShade crosire dummy data" * 10)
        (target_dir / "ReShade.ini").write_text("[ADDON]\nLoadFromDllMain=renodx-mfgunlock.addon64\n", encoding="utf-8")

        game = GameInfo(
            name="燕云十六声",
            source="Custom",
            install_dir=str(target_dir),
            target_dir=str(target_dir),
            exe_path=str(target_dir / "yysls.exe"),
            exe_name="yysls.exe",
            qualification=QualificationStatus.QUALIFIED
        )

        updater = ComponentUpdater()
        patcher = PatchEngine(updater)

        # Patch with Mode C (OPTISCALER_FSR)
        ok, msg = patcher.patch_game(game, BackendType.OPTISCALER_FSR)
        assert ok, f"Patching Mode C failed: {msg}"
        print(f"  -> Patch applied successfully: {msg.splitlines()[0]}")

        # 1. Mutual Exclusivity: renodx addon must be purged!
        assert not (target_dir / "renodx-mfgunlock.addon64").exists(), "renodx-mfgunlock.addon64 must be purged in Mode C!"

        # 2. ReShade dxgi.dll backed up and OptiScaler installed as dxgi.dll
        assert (target_dir / "dxgi.dll.reshade_bak").exists(), "ReShade dxgi.dll should be backed up"
        assert (target_dir / "dxgi.dll").exists(), "OptiScaler should be deployed as dxgi.dll"

        # 3. v1.2.6 fakenvapi gating: XeFG requires fakenvapi (OptiScaler template:
        #    "xefg - requires libxess_fg.dll, libxell.dll and latest fakenvapi dll").
        #    It is side-loaded by name, not installed as nvapi64.dll.
        opti_dir = updater.get_latest_cached_dir(BackendType.OPTISCALER_FSR)
        opti_path = Path(opti_dir) if opti_dir else Path(".")
        if (opti_path / "fakenvapi.dll").exists() or (opti_path / "OptiScaler" / "fakenvapi.dll").exists():
            assert (target_dir / "fakenvapi.dll").exists(), "fakenvapi.dll must be deployed for XeFG output!"
            assert (target_dir / "fakenvapi.ini").exists(), "fakenvapi.ini must be deployed for XeFG output!"
        # The legacy dual-config alias must be purged on every Mode C deployment
        assert not (target_dir / "nvngx.ini").exists(), "nvngx.ini must never be written in Mode C!"

        # 4. Anti-crash INI configurations (v0.9.4 real key names only)
        opti_ini_clean = (target_dir / "OptiScaler.ini").read_text(encoding="utf-8").replace(" ", "")
        assert "TargetProcessName=yysls.exe" in opti_ini_clean, "TargetProcessName must be set to yysls.exe"
        assert "UseDelayedInit" not in IniConfigManager.read_ini_sections(target_dir / "OptiScaler.ini").get("Hotfix", {}), \
            "UseDelayedInit belongs to [Dx11withDx12]; it must not be injected into [Hotfix]"
        assert "SkipFirstFrames=5" in opti_ini_clean, "SkipFirstFrames must be 5"
        assert "EarlyHooking=false" in opti_ini_clean, "EarlyHooking must be false"
        assert "UseNtdllHooks=false" in opti_ini_clean, "UseNtdllHooks must be false"

        # 5. v1.2.6 menu scale + XeFG init values written before launch
        assert "[Menu]" in opti_ini_clean
        assert "Scale=2.0" in opti_ini_clean, "4K menu scale must be written as 2.0"
        assert "InterpolationCount=2" in opti_ini_clean, "XeFG must request the factory 3X interpolation count"

        # 5. Clean rollback verification: newly created bridge files removed, original pre-existing files restored
        ok_rb, msg_rb = patcher.rollback_engine.rollback(str(target_dir), "yysls.exe")
        assert ok_rb, f"Rollback failed: {msg_rb}"
        assert (target_dir / "dxgi.dll").read_bytes() == b"ReShade crosire dummy data" * 10, "Original pre-existing dxgi.dll must be restored on rollback!"
        assert not (target_dir / "OptiScaler.ini").exists(), "OptiScaler.ini must be removed on rollback"
        assert not (target_dir / "dlssg_to_fsr3_amd_is_better.dll").exists(), "Bridge DLL must be removed"
        print("  -> Mode C mutual exclusivity, anti-crash configs, and rollback passed 100%!")
    finally:
        cleanup_pending_files(str(target_dir))
        shutil.rmtree(td, ignore_errors=True)


